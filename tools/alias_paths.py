#!/usr/bin/env python3
"""The globals that live inside g_main_win, as offset expressions (roadmap W9).

    python3 tools/alias_paths.py        (in the Linux machine: needs python3-pyelftools and the
                                         Winelib objects, build/obj-winegcc, built with -g)

src/gen/aliases.txt places each such global at the game's offset in MainWin (--defsym). That is
the layout only where a pointer is 4 bytes: MainWin holds pointers, so on x86_64 everything after
the first one moves. This reads MainWin's layout from the i386 object's debug information --
the game's layout, the size checks say so -- finds for each offset the outermost member or base
class that starts there, and writes the path as a C++ constant expression each target's
compiler can evaluate (src/gen/alias_paths.txt: name container game_offset expression):
    __builtin_offsetof(MainWin, map.region)      a member path
    + sizeof(GRPort)                              a second base class (packed: its offset is the
                                                  size of the bases before it)
tools/undefined.py evaluates them for a 64-bit target; for i386 they must equal the game's.
"""
import os
import sys
from elftools.elf.elffile import ELFFile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OBJ = os.path.join(ROOT, "build", "obj-winegcc", "game", "create_game_globals.o")
OUT = os.path.join(ROOT, "src", "gen", "alias_paths.txt")


def attr(die, name, default=None):
    a = die.attributes.get(name)
    return a.value if a else default


def strip(die):
    """through typedefs and cv-qualifiers to the type itself"""
    while die is not None and die.tag in ("DW_TAG_typedef", "DW_TAG_const_type", "DW_TAG_volatile_type"):
        die = die.get_DIE_from_attribute("DW_AT_type") if "DW_AT_type" in die.attributes else None
    return die


def name_of(die):
    n = attr(die, "DW_AT_name")
    return n.decode() if n else None


def children(t):
    """(kind, name, offset, type die) for a class's bases and data members, in layout order"""
    out = []
    for c in t.iter_children():
        if c.tag in ("DW_TAG_inheritance", "DW_TAG_member") and "DW_AT_data_member_location" in c.attributes:
            if attr(c, "DW_AT_external") or attr(c, "DW_AT_declaration"):
                continue
            out.append(("base" if c.tag == "DW_TAG_inheritance" else "member", name_of(c),
                        attr(c, "DW_AT_data_member_location"), strip(c.get_DIE_from_attribute("DW_AT_type"))))
    return sorted(out, key=lambda x: x[2])


def size_of(t):
    return attr(t, "DW_AT_byte_size")


def find(t, off):
    """the path to offset `off` inside type t: the outermost member/base starting at it"""
    if off == 0:
        return []
    if t.tag == "DW_TAG_array_type":
        elem = strip(t.get_DIE_from_attribute("DW_AT_type"))
        n = size_of(elem)
        i, rest = divmod(off, n)
        return [("index", i, elem)] + find(elem, rest)
    for kind, name, at, ct in children(t):
        sz = size_of(ct)
        if sz is None:
            continue
        if at <= off < at + sz:
            return [(kind, name if kind == "member" else name_of(ct), ct, at, t)] + find(ct, off - at)
    raise SystemExit("no member at offset %#x of %s" % (off, name_of(t)))


def expression(root, path):
    """a C++ constant expression for the path's offset in `root`"""
    terms, designator, owner = [], "", root
    for step in path:
        if step[0] == "index":
            designator += "[%d]" % step[1]
            continue
        kind, name, ct, at, parent = step
        if kind == "member":
            designator += ("." if designator else "") + name
        else:
            if designator:
                terms.append("__builtin_offsetof(%s, %s)" % (owner, designator))
            # the bases before this one, packed
            before = [n for k, n0, a, c in children(parent) if k == "base" and a < at for n in [name_of(c)]]
            terms += ["sizeof(%s)" % b for b in before]
            owner, designator = name, ""
    if designator:
        terms.append("__builtin_offsetof(%s, %s)" % (owner, designator))
    return " + ".join(terms) or "0"


def main():
    with open(OBJ, "rb") as f:
        dw = ELFFile(f).get_dwarf_info()
        mainwin = None
        for cu in dw.iter_CUs():
            for die in cu.iter_DIEs():
                if die.tag == "DW_TAG_class_type" and name_of(die) == "MainWin" and size_of(die):
                    mainwin = die
                    break
        if mainwin is None:
            sys.exit("no MainWin with a size in %s (built with -g?)" % OBJ)
        lines = ["# GENERATED by tools/alias_paths.py from MainWin's debug information (i386): name container",
                 "# game_offset expression -- each global inside g_main_win as an offset expression a 64-bit",
                 "# target's compiler evaluates (tools/undefined.py); on i386 it equals the game's offset"]
        for line in open(os.path.join(ROOT, "src", "gen", "aliases.txt")):
            if line.startswith("#") or not line.strip():
                continue
            n, c, off = line.split()
            if c != "g_main_win":
                continue
            lines.append("%s %s %s %s" % (n, c, off, expression("MainWin", find(mainwin, int(off, 16)))))
        open(OUT, "w").write("\n".join(lines) + "\n")
        print("\n".join(lines[3:]))


main()

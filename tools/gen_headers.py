def fix_model_records(text):
    for name, old, new, why in MODEL_FIXES:
        m = re.search(r"typedef struct \{[^{}]*\} %s;" % re.escape(name), text)
        if not m or m.group(0).count(old) != 1:
            sys.exit("gen_headers: MODEL_FIXES: %s has no `%s`" % (name, old))
        rec = m.group(0).replace(old, new + "   /* PORT: %s */" % why)
        text = text[:m.start()] + rec + text[m.end():]
    return text


def corpus_records():
    t = strip_comments(open(os.path.join(INC, "records.h")).read())
    return set(re.findall(r"\}\s*(\w+)\s*;", t))


def drop_records(text, names):
    """colonization.h without its `typedef struct {...} Name;` for each name in `names`
    (an alias keeps a typedef to the corpus's record)."""
    out, i = [], 0
    for m in re.finditer(r"typedef struct\s*\w*\s*\{", text):
        if m.start() < i:
            continue
        d = 0
        for j in range(m.end() - 1, len(text)):
            if text[j] == "{":
                d += 1
            elif text[j] == "}":
                d -= 1
                if d == 0:
                    break
        e = text.index(";", j) + 1
        name = re.match(r"\}\s*(\w+)", text[j:]).group(1)
        if name in names:
            out.append(text[i:m.start()])
            if name in ALIASES:
                out.append("typedef %s %s;   /* PORT: the corpus's name for this record */" % (ALIASES[name], name))
            else:
                out.append("/* PORT: %s is records.h's (the corpus's member names, the model's size) */" % name)
            i = e
    out.append(text[i:])
    return "".join(out)


def known_types(src):
    """(types a C file sees, types a C++ file sees) once colonization.h has included w16types.h,
    records.h and classes.h."""
    cls = strip_comments(open(os.path.join(INC, "classes.h")).read())
    split = cls.index("#else")
    common = (defined_types(src) | defined_types(open(os.path.join(INC, "w16types.h")).read())
              | defined_types(open(os.path.join(INC, "records.h")).read()) | set(ALIASES)
              | {"i16", "u16", "i32", "u32"})
    classes = (set(re.findall(r"\bclass\s+(\w+)", cls[:split])) | set(CORPUS_CLASSES)) - local_typedef_names(True)
    views = (defined_types(cls[split:]) | set(CORPUS_VIEWS)) - local_typedef_names(False)
    # C++ gets each class forward-declared, which a file's own definition can follow -- except
    # a class some C++ file still views as `typedef struct {...} Name;`, which a forward
    # `class Name;` would contradict. C gets classes.h's views, included from the header --
    # except a view some C file still defines for itself.
    return common | views, common | classes


def type_names(decl, name):
    decl = re.sub(r'"[^"]*"', "", decl)
    decl = re.sub(r"\b(?:struct|union)\s+\w+", "", decl)     # tags: guarded() checks those
    return {w for w in re.findall(r"\b([A-Za-z_]\w*)\b", decl)
            if w != name and w[0].isupper()} - {"extern"}


def guarded(decl, name, known_c, known_cpp):
    """The declaration as it may appear in the header: plain, C++-only, or None."""
    # an elaborated `struct tag` here would be a new, prototype-scoped type in C: only tags
    # some header defines may appear
    tags = set(re.findall(r"\b(?:struct|union)\s+(\w+)", decl))
    if tags - set(TAGS_KNOWN):
        return None
    types = type_names(decl, name)
    if types <= known_c and types <= known_cpp:
        return decl
    if types <= known_cpp:
        return "#ifdef __cplusplus\n%s\n#endif" % decl
    if types <= known_c:
        return "#ifndef __cplusplus\n%s\n#endif" % decl
    return None



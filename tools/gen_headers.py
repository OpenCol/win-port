def strip_comments(t):
    t = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), t, flags=re.S)
    return re.sub(r"//[^\n]*", "", t)


# ---------------------------------------------------------------- widths

def widen_member(decl):
    """A member declaration's Borland 16-bit integer types, spelled for a modern compiler.
    `int`, `signed`, `signed int` -> i16; `unsigned`, `unsigned int` -> u16. `short`, `long`,
    `char` and their combinations are already the same width."""
    d = decl
    d = re.sub(r"\bunsigned\s+int\b", "u16", d)
    d = re.sub(r"\bsigned\s+int\b", "i16", d)
    d = re.sub(r"\bunsigned\b(?!\s+(?:char|short|long|int)\b)", "u16", d)
    d = re.sub(r"\bsigned\b(?!\s+(?:char|short|long|int)\b)", "i16", d)
    d = re.sub(r"(?<!\bshort\s)(?<!\blong\s)\bint\b", "i16", d)
    return d


def widen_body(body):
    """Each `;`-terminated member in a record or class body through widen_member, leaving
    anything with parentheses (a method, a function pointer's parameters) alone."""
    out, depth, cur = [], 0, ""
    for ch in body:
        cur += ch
        if ch in "({":
            depth += 1
        elif ch in ")}":
            depth -= 1
        elif ch == ";" and depth == 0:
            out.append(cur if "(" in cur else widen_member(cur))
            cur = ""
    out.append(cur if "(" in cur else widen_member(cur))
    return "".join(out)


def widen_records(text):
    """Every `typedef struct ... {body} Name;` and `class Name ... {body};` in text, widened."""
    res, i = [], 0
    for m in re.finditer(r"(?:typedef\s+struct\s*\w*|class\s+\w+[^{;]*|struct\s+\w+)\s*\{", text):
        if m.start() < i:
            continue
        o = m.end() - 1
        d = 0
        for j in range(o, len(text)):
            if text[j] == "{":
                d += 1
            elif text[j] == "}":
                d -= 1
                if d == 0:
                    break
        res.append(text[i:o + 1])
        res.append(widen_body(text[o + 1:j]))
        i = j
    res.append(text[i:])
    return "".join(res)


PACK_OPEN = "#pragma pack(push, 1)\n"
PACK_CLOSE = "#pragma pack(pop)\n"


def borland_pragmas(text):
    """`#pragma option -a` (word alignment) / `-a-` (byte) as the packing a modern compiler reads."""
    text = re.sub(r"^#pragma option -a-\s*$", "#pragma pack(1)", text, flags=re.M)
    return re.sub(r"^#pragma option -a\s*$", "#pragma pack(2)", text, flags=re.M)


# ---------------------------------------------------------------- the four headers

def src_files():
    """The imported sources (src/<layer>/*.c), not src/gen: what is generated from them is
    not evidence about them."""
    return sorted(p for p in glob.glob(os.path.join(ROOT, "src", "*", "*.c"))
                  if os.path.basename(os.path.dirname(p)) != "gen")


def defined_types(text):
    t = strip_comments(text)
    return (set(re.findall(r"\}\s*(\w+)\s*;", t)) | set(re.findall(r"typedef[^;{}()]*?\b(\w+)\s*;", t))
            | set(re.findall(r"typedef[^;{}()]*\(\s*(?:far\s+|__far\s+)?\*\s*(\w+)\s*\)\s*\([^;{}]*\)\s*;", t))
            | set(re.findall(r"\bstruct\s+(\w+)\s*\{", t)))


_LOCAL_TYPEDEFS = None


def local_typedef_names(cpp=None):
    """Names some file in src/ defines for itself as a typedef or struct (a local view): of the
    C++ files (cpp=True), the C files (False), or all."""
    global _LOCAL_TYPEDEFS
    if _LOCAL_TYPEDEFS is None:
        names = {True: set(), False: set()}
        for p in src_files():
            t = open(p, errors="replace").read()
            names[bool(re.search(r"flags:.*-P\b", t[:4000]))] |= defined_types(t)
        _LOCAL_TYPEDEFS = names
    if cpp is None:
        return _LOCAL_TYPEDEFS[True] | _LOCAL_TYPEDEFS[False]
    return _LOCAL_TYPEDEFS[cpp]


def signature(decl):
    """A function declaration's types without its parameter names, extern or spacing:
    `extern "C" int f(char *s, int n);` -> ('int', 'f', ('char*', 'int'))."""
    d = re.sub(r'\bextern\s+(?:"C"\s+)?', "", decl).strip().rstrip(";").strip()
    m = re.match(r"(.*?)\b(\w+)\s*\((.*)\)$", d, re.S)
    if not m:
        return None
    params = []
    for prm in [x.strip() for x in m.group(3).split(",")] if m.group(3).strip() else []:
        prm = re.sub(r"\s+", " ", prm)
        if prm not in ("void", "...") and re.search(r"[\w\]]\s*$", prm) and len(re.findall(r"\w+", prm)) > 1:
            prm = re.sub(r"\s*\b\w+\s*((?:\[[^\]]*\])*)$", r"\1", prm)    # drop the name, keep [] dims
        params.append(re.sub(r"\s+", "", prm))
    return (re.sub(r"\s+", "", m.group(1)), m.group(2), tuple(params) if params != ["void"] else ())


def file_scope(text):
    """text with comments and every brace block's inside blanked (offsets and lines kept), so
    only file-scope statements are left to match."""
    t = strip_comments(text)
    out, depth = [], 0
    for ch in t:
        if ch == "{":
            depth += 1
            out.append(ch if depth == 1 else " ")
        elif ch == "}":
            depth -= 1
            out.append(ch if depth == 0 else " ")
        elif depth and ch != "\n":
            out.append(" ")
        else:
            out.append(ch)
    return "".join(out)


def file_typedefs():
    """{name: {typedef statement}} of the one-line typedefs files in src/ write at file scope."""
    out = {}
    for p in src_files():
        for m in re.finditer(r"^[ \t]*(typedef [^;{}]*;)", file_scope(open(p, errors="replace").read()), re.M):
            s = re.sub(r"\s+", " ", m.group(1)).strip()
            n = re.search(r"\(\s*\*\s*(\w+)\s*\)\s*\(|(\w+)\s*;$", s)
            if n:
                out.setdefault(n.group(1) or n.group(2), set()).add(s)
    return out


def global_definitions():
    """{name: `extern TYPE name[dims];`} for every global some file in src/ defines (not
    static, not extern): the type its definition gives it, widened. Constructor arguments and
    initialisers are dropped."""
    out = {}
    for p in src_files():
        scope = file_scope(open(p, errors="replace").read())
        for m in re.finditer(r"(?:^|;|\})[ \t\n]*((?!extern\b|static\b|typedef\b|return\b)[A-Za-z_][\w \t*]*?)\b(g_\w+)"
                             r"\s*((?:\[[^\]]*\]\s*)*)(?:\([^;{}]*\))?\s*(?:=[^;]*)?;", scope, re.M):
            head = re.sub(r"\s+", " ", m.group(1)).strip()
            if not head or re.search(r"\b(class|struct|union|enum)\s*$", head):
                continue
            # exactly as defined: the definition in src/ still says `int`, and a header that said
            # i16 would contradict it (the sources' ints are widened together, later)
            out[m.group(2)] = "extern %s %s%s;" % (head, m.group(2), re.sub(r"\s+", "", m.group(3)))
    return out


def file_declarations():
    """(variables, functions) some file in src/ declares itself at file scope: an `extern`
    variable, or a prototype (not a definition). Functions map to the set of signatures the
    files give them."""
    vars_, funcs = {}, {}
    for p in src_files():
        t = file_scope(open(p, errors="replace").read())
        for m in re.finditer(r"^[ \t]*((?:extern\s+(?:\"C\"\s+)?)?[A-Za-z_][^;{}()#=]*?\b([A-Za-z_]\w*)\s*\([^;{}]*\)\s*;)", t, re.M):
            funcs.setdefault(m.group(2), set()).add(signature(m.group(1)))
        for m in re.finditer(r"^[ \t]*(extern\s+(?!\"C\")[^;(){}=]*?\b(\w+)\s*(?:\[[^\]]*\]\s*)*;)", t, re.M):
            vars_.setdefault(m.group(2), set()).add(re.sub(r"\s+", " ", m.group(1)).strip())
        # a pointer to a function: `extern void (*g_cd_done_cb)(void);`
        for m in re.finditer(r"^[ \t]*(extern\s+(?!\"C\")[^;(){}=]*\(\s*\*\s*(g_\w+)\s*\)\s*\([^;{}]*\)\s*;)", t, re.M):
            vars_.setdefault(m.group(2), set()).add(re.sub(r"\s+", " ", m.group(1)).strip())
    return vars_, funcs


def definition_heads():
    """{function name: its definition's head} over src/ (the ported corpus)."""
    heads = {}
    for p in src_files():
        t = strip_comments(open(p, errors="replace").read())
        for m in re.finditer(r"^([A-Za-z_][^;{}()#=]*?\b([A-Za-z_]\w*)\s*\([^;{}()]*\))\s*\{", t, re.M):
            name = m.group(2)
            if name in ("if", "while", "for", "switch", "return", "sizeof"):
                continue
            # the header's declarations all sit in one extern "C" block: the definition's own
            # linkage spelling is not part of its head
            head = re.sub(r'^extern\s+"C"\s+', "", re.sub(r"\s+", " ", m.group(1)).strip())
            heads.setdefault(name, set()).add(head)
    return {n: next(iter(h)) for n, h in heads.items() if len(h) == 1}



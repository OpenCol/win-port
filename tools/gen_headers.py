#!/usr/bin/env python3
"""Generate include/gen/: the port's versions of the imported headers, which shadow them.

    python3 tools/gen_headers.py            # write include/gen/
    python3 tools/gen_headers.py --check    # fail if include/gen/ is not what this generates (CI)

The import brings two kinds of header from col-win-re, and they disagree:
  * include/colonization.h, generated there from the model (analysis/model.json): every record
    PACKED and spelled with modern widths (a Borland `int` is 16 bits, so it says int16_t);
  * include/records.h, classes.h and w16types.h, written for Borland C++ 4.52, where `int`
    and `unsigned` are 16 bits. On a modern compiler their layouts are wrong.
The ported sources include colonization.h first and the Borland headers after it, so every
record defined in both is defined twice. The import is never edited (its files are
reproduced byte for byte); the compile puts include/gen ahead of include instead, and this
writes there:

  colonization.h  the imported one with two fixes: its size checks work in C++03 too
                  (_Static_assert is C11, and the 436 C++ reconstructions stopped at it),
                  and a prototype of a function src/ defines takes the definition's head
                  (the model's prototypes lag the corpus).
  records.h       only the records colonization.h does not define, packed, with the
                  Borland 16-bit widths spelled i16/u16.
  classes.h       the classes (C++) and their C views (C), the same width rule for data
                  members, Borland's `#pragma option -a`/`-a-` as pack(2)/pack(1).
  w16types.h      the Win16 records (RECT, POINT, PAINTSTRUCT...) with Win16 widths, packed.
Parameters of methods keep the source's spelling: they must match their definitions in src/.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, "include")
GEN = os.path.join(INC, "gen")
BANNER = "/* GENERATED by tools/gen_headers.py from include/%s -- do not edit. */\n"


def strip_comments(t):
    t = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), t, flags=re.S)
    return re.sub(r"//[^\n]*", "", t)


# ---------------------------------------------------------------- widths

def widen_member(decl):
    """A member declaration's Borland 16-bit integer types, spelled for a modern compiler.
    `int`, `signed`, `signed int` -> i16; `unsigned`, `unsigned int` -> u16. `short`, `long`,
    `char` and their combinations are already the same width."""
    d = decl
    d = re.sub(r"\bunsigned\s+int\b", "u16", d)
    d = re.sub(r"\bsigned\s+int\b", "i16", d)
    d = re.sub(r"\bunsigned\b(?!\s+(?:char|short|long|int)\b)", "u16", d)
    d = re.sub(r"\bsigned\b(?!\s+(?:char|short|long|int)\b)", "i16", d)
    d = re.sub(r"(?<!\bshort\s)(?<!\blong\s)\bint\b", "i16", d)
    return d


def widen_body(body):
    """Each `;`-terminated member in a record or class body through widen_member, leaving
    anything with parentheses (a method, a function pointer's parameters) alone."""
    out, depth, cur = [], 0, ""
    for ch in body:
        cur += ch
        if ch in "({":
            depth += 1
        elif ch in ")}":
            depth -= 1
        elif ch == ";" and depth == 0:
            out.append(cur if "(" in cur else widen_member(cur))
            cur = ""
    out.append(cur if "(" in cur else widen_member(cur))
    return "".join(out)


def widen_records(text):
    """Every `typedef struct ... {body} Name;` and `class Name ... {body};` in text, widened."""
    res, i = [], 0
    for m in re.finditer(r"(?:typedef\s+struct\s*\w*|class\s+\w+[^{;]*|struct\s+\w+)\s*\{", text):
        if m.start() < i:
            continue
        o = m.end() - 1
        d = 0
        for j in range(o, len(text)):
            if text[j] == "{":
                d += 1
            elif text[j] == "}":
                d -= 1
                if d == 0:
                    break
        res.append(text[i:o + 1])
        res.append(widen_body(text[o + 1:j]))
        i = j
    res.append(text[i:])
    return "".join(res)


PACK_OPEN = "#pragma pack(push, 1)\n"
PACK_CLOSE = "#pragma pack(pop)\n"


def borland_pragmas(text):
    """`#pragma option -a` (word alignment) / `-a-` (byte) as the packing a modern compiler reads."""
    text = re.sub(r"^#pragma option -a-\s*$", "#pragma pack(1)", text, flags=re.M)
    return re.sub(r"^#pragma option -a\s*$", "#pragma pack(2)", text, flags=re.M)


# ---------------------------------------------------------------- the four headers

def defined_types(text):
    t = strip_comments(text)
    return (set(re.findall(r"\}\s*(\w+)\s*;", t)) | set(re.findall(r"typedef[^;{}()]*?\b(\w+)\s*;", t))
            | set(re.findall(r"\bstruct\s+(\w+)\s*\{", t)))


def definition_heads():
    """{function name: its definition's head} over src/ (the ported corpus)."""
    heads = {}
    for p in glob.glob(os.path.join(ROOT, "src", "*", "*.c")):
        t = strip_comments(open(p, errors="replace").read())
        for m in re.finditer(r"^([A-Za-z_][^;{}()#=]*?\b([A-Za-z_]\w*)\s*\([^;{}()]*\))\s*\{", t, re.M):
            name = m.group(2)
            if name in ("if", "while", "for", "switch", "return", "sizeof"):
                continue
            heads.setdefault(name, set()).add(re.sub(r"\s+", " ", m.group(1)).strip())
    return {n: next(iter(h)) for n, h in heads.items() if len(h) == 1}


# The model's names for records the corpus has since unified under another name (same size,
# same bytes): colonization.h's definition becomes a typedef of the corpus's record.
ALIASES = {"Nation34": "NationText"}

# Records whose size the model and the corpus disagree on. The corpus's definition compiled to
# the shipped bytes, so the port takes it, and the model's size check for it is left out.
# Each is reported upstream (UPSTREAM.md).
SIZE_FROM_CORPUS = {
    "MemBlock": "the model sized it from its first member (2); the corpus record is 14 bytes",
    "Settlement": "the model's 32-byte record is not the 18-byte settlement the corpus indexes",
    "WinGRec": "the model has 8 bytes; the corpus record has five words",
}


def corpus_records():
    t = strip_comments(open(os.path.join(INC, "records.h")).read())
    return set(re.findall(r"\}\s*(\w+)\s*;", t))


def drop_records(text, names):
    """colonization.h without its `typedef struct {...} Name;` for each name in `names`
    (an alias keeps a typedef to the corpus's record)."""
    out, i = [], 0
    for m in re.finditer(r"typedef struct\s*\w*\s*\{", text):
        if m.start() < i:
            continue
        d = 0
        for j in range(m.end() - 1, len(text)):
            if text[j] == "{":
                d += 1
            elif text[j] == "}":
                d -= 1
                if d == 0:
                    break
        e = text.index(";", j) + 1
        name = re.match(r"\}\s*(\w+)", text[j:]).group(1)
        if name in names:
            out.append(text[i:m.start()])
            if name in ALIASES:
                out.append("typedef %s %s;   /* PORT: the corpus's name for this record */" % (ALIASES[name], name))
            else:
                out.append("/* PORT: %s is records.h's (the corpus's member names, the model's size) */" % name)
            i = e
    out.append(text[i:])
    return "".join(out)


def gen_colonization():
    src = open(os.path.join(INC, "colonization.h")).read()
    out = drop_records(src, corpus_records() | set(ALIASES))
    out = out.replace('#include "w16types.h"', '#include "w16types.h"\n#include "records.h"', 1)
    for name, why in SIZE_FROM_CORPUS.items():
        out, n = re.subn(r"_Static_assert\(sizeof\(%s\) == \d+, \"[^\"]*\"\);" % re.escape(name),
                         "/* PORT: no size check for %s: %s */" % (name, why), out)
        if n != 1:
            sys.exit("gen_headers: no size check for %s in colonization.h" % name)
    out = out.replace("_Static_assert(", "PORT_SIZE_ASSERT(")
    macro = ("/* PORT: _Static_assert is C11; the C++ reconstructions compile as C++03. */\n"
             "#ifndef PORT_SIZE_ASSERT\n#ifdef __cplusplus\n"
             "#define PORT_SIZE_ASSERT(cond, msg) typedef char PORT_SA_CAT(port_size_assert_, __LINE__)[(cond) ? 1 : -1]\n"
             "#define PORT_SA_CAT(a, b) PORT_SA_CAT2(a, b)\n#define PORT_SA_CAT2(a, b) a##b\n"
             "#else\n#define PORT_SIZE_ASSERT(cond, msg) _Static_assert(cond, msg)\n#endif\n#endif\n\n")
    first = out.index("#include <stdint.h>")
    out = out[:first] + macro + out[first:]
    # prototypes the corpus has moved on from: a function src/ defines gets its definition's head
    heads = definition_heads()
    fixed, dropped = [], []
    # the types a prototype here may name: colonization.h's own and w16types.h's (it is
    # included before records.h and classes.h, so their types are not known yet)
    known = defined_types(src) | defined_types(open(os.path.join(INC, "w16types.h")).read())

    def proto(m):
        name = m.group(2)
        want = heads.get(name)
        if want and re.sub(r"\s+", " ", m.group(1)).strip() != want:
            types = {w for w in re.findall(r"\b([A-Z]\w*)\b", want) if w != name}
            if types <= known:
                fixed.append(name)
                return "extern %s;" % want
            dropped.append(name)
            return "/* PORT: %s's prototype here was stale, and its definition names types declared later */" % name
        return m.group(0)
    out = re.sub(r"^extern\s+([^;{}()]*?\b([A-Za-z_]\w*)\s*\([^;{}()]*\))\s*;", proto, out, flags=re.M)
    return BANNER % "colonization.h" + out, (fixed, dropped)


def gen_records(col_types):
    src = open(os.path.join(INC, "records.h")).read()
    keep, dropped = [], []
    # each statement of the header: a record dropped when colonization.h defines it
    t = src
    pos = 0
    pieces = []
    for m in re.finditer(r"typedef\s+struct\s*\w*\s*\{", t):
        if m.start() < pos:
            continue
        d = 0
        for j in range(m.end() - 1, len(t)):
            if t[j] == "{":
                d += 1
            elif t[j] == "}":
                d -= 1
                if d == 0:
                    break
        e = t.index(";", j) + 1
        name = re.match(r"\}\s*(\w+)", t[j:]).group(1)
        pieces.append((m.start(), e, name))
        pos = e
    out, last = [], 0
    for s, e, name in pieces:
        out.append(t[last:s])
        out.append(t[s:e])
        keep.append(name)
        if name in col_types:
            dropped.append(name)       # colonization.h's own definition of it goes
        last = e
    out.append(t[last:])
    text = widen_records("".join(out))
    text = text.replace('#include "w16types.h"', '#include "w16types.h"\n#include "port/types.h"\n' + PACK_OPEN, 1)
    text = text.replace("\n#endif", "\n" + PACK_CLOSE + "#endif", 1) if "\n#endif" in text else text + PACK_CLOSE
    return BANNER % "records.h" + text, keep, dropped


def gen_classes():
    src = open(os.path.join(INC, "classes.h")).read()
    text = borland_pragmas(widen_records(src))
    text = text.replace('#include "records.h"', '#include "records.h"\n#include "port/types.h"\n' + PACK_OPEN, 1)
    i = text.rindex("#endif")
    text = text[:i] + PACK_CLOSE + text[i:]
    return BANNER % "classes.h" + text


def gen_w16types():
    src = open(os.path.join(INC, "w16types.h")).read()
    text = widen_records(src)
    i = text.index("#define W16TYPES_H") + len("#define W16TYPES_H\n")
    text = text[:i] + '\n#include "port/types.h"\n' + PACK_OPEN + text[i:]
    j = text.rindex("#endif")
    text = text[:j] + PACK_CLOSE + text[j:]
    return BANNER % "w16types.h" + text


def generate():
    col, fixed = gen_colonization()
    col_types = defined_types(open(os.path.join(INC, "colonization.h")).read())
    rec, keep, dropped = gen_records(col_types)
    files = {"colonization.h": col, "records.h": rec, "classes.h": gen_classes(), "w16types.h": gen_w16types()}
    return files, {"prototypes_fixed": fixed, "records_kept": keep, "records_dropped": dropped}


def main(argv):
    files, info = generate()
    if "--check" in argv:
        stale = [n for n, t in files.items()
                 if not os.path.exists(os.path.join(GEN, n)) or open(os.path.join(GEN, n)).read() != t]
        print("include/gen: %s" % ("current" if not stale else "STALE: " + ", ".join(stale)))
        return 1 if stale else 0
    os.makedirs(GEN, exist_ok=True)
    for n, t in files.items():
        open(os.path.join(GEN, n), "w").write(t)
    print("include/gen: %s; colonization.h: %d prototypes take their definition's head, %d stale ones "
          "dropped; records.h keeps %d, leaves %d to colonization.h" % (
              ", ".join(sorted(files)), len(info["prototypes_fixed"][0]), len(info["prototypes_fixed"][1]),
              len(info["records_kept"]), len(info["records_dropped"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

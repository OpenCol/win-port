def corpus_globals():
    p = os.path.join(ROOT, "import", "globals.json")
    if not os.path.exists(p):
        return {}
    import json
    out = {}

    def norm(d):            # 0x10 and 16 are one dimension
        return re.sub(r"\[(0x[0-9a-fA-F]+)\]", lambda m: "[%d]" % int(m.group(1), 16), d)
    for name, spellings in json.load(open(p)).items():
        votes = {}
        for d, n in spellings.items():
            votes[norm(d)] = votes.get(norm(d), 0) + n
        # the spelling with the most dimensions where one only flattens another (`T x[]` against
        # `T x[][16]`, same element type); else the most files'
        bases = {re.sub(r"(\[[^\]]*\])+", "", d) for d in votes}
        if len(bases) == 1:
            best = sorted(votes, key=lambda d: (-d.count("["), -votes[d], d))[0]
        else:
            best = sorted(votes.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
        # as the corpus writes it: the sources' `int` is widened together with the functions
        # that take these globals, not here alone
        out[name] = best
    return out


def gen_colonization():
    src = open(os.path.join(INC, "colonization.h")).read()
    known_c, known_cpp = known_types(src)
    out = drop_records(fix_model_records(src), corpus_records() | set(ALIASES))
    cls_names = sorted((set(re.findall(r"\bclass\s+(\w+)", strip_comments(open(os.path.join(INC, "classes.h")).read())))
                        | set(CORPUS_CLASSES)) - local_typedef_names(True))
    fwd = ("#ifdef __cplusplus\n" + "".join("class %s;\n" % c for c in cls_names) +
           "#else\n#include \"classes.h\"   /* PORT: the C views */\n#endif\n")
    # the tags prototypes may name, declared at file scope so each is one type, not a new one
    # per prototype (C) -- C++ files complete them as classes or structs
    tags = "".join("struct %s;\n" % t for t in TAGS_KNOWN if t != "DlgControl")
    out = out.replace('#include "w16types.h"', '#include "w16types.h"\n#include "records.h"\n' + fwd + tags, 1)
    # typedefs the header and the files both define: when every file spells it one way, that
    # spelling (an identical typedef may be repeated, a different one may not)
    ftd = file_typedefs()

    def td_line(m):
        spell = ftd.get(m.group(1))
        if spell and len(spell) == 1:
            s = next(iter(spell))
            if re.sub(r"\s+", " ", m.group(0)).strip() != s:
                return s + "   /* PORT: the files' typedef */"
        return m.group(0)
    out = re.sub(r"^typedef [^;{}]*?\(\s*\*\s*(\w+)\s*\)\s*\([^;{}]*\)\s*;", td_line, out, flags=re.M)
    out = re.sub(r"^typedef struct (\w+)_s \1;", td_line, out, flags=re.M)
    # globals: the type a global's definition in src/ gives it; else the one spelling every file
    # in src/ that declares it uses; else the corpus's (most files'). A global the files in src/
    # declare two ways is left to them.
    own_vars, own_funcs = file_declarations()
    defs = global_definitions()
    cg = {}
    for n, d in corpus_globals().items():
        if n in own_vars and len(own_vars[n]) > 1:
            continue
        cg[n] = d
    for n, spells in own_vars.items():
        if len(spells) == 1 and n.startswith("g_"):
            cg[n] = next(iter(spells))          # as the files in src/ write it
    users = corpus_globals()
    # a function-pointer global the files declare one way, where the header says something else
    for n, spells in own_vars.items():
        if len(spells) == 1 and "(*" in next(iter(spells)).replace(" ", ""):
            out = re.sub(r"^extern [^;\n]*\b%s\b[^;\n]*;.*$" % re.escape(n),
                         next(iter(spells)) + "   /* PORT: the files' type */", out, count=1, flags=re.M)
    for n, d in defs.items():
        u = users.get(n)
        # the definition's `T x[1]` against its users' `T x`: the users' (one object, as every
        # caller takes it; the defining file follows, with a PORT: edit)
        if u and "[" in d and "[" not in u:
            continue
        if n not in own_vars or own_vars[n] <= {d}:
            cg[n] = d
    # the stubs' scratch globals belong to each file that writes one, with its own type
    cg = {n: d for n, d in cg.items() if not n.startswith("g_stub")}
    gfix = []

    def glob_decl(m):
        name = m.group(2)
        want = cg.get(name)
        if not want or re.sub(r"\s+", " ", m.group(0)).strip() == want:
            return m.group(0)
        g = guarded(want, name, known_c, known_cpp)
        if g is None:
            return m.group(0)
        gfix.append(name)
        if g.startswith("#ifdef"):
            return "#ifdef __cplusplus\n%s\n#else\n%s\n#endif" % (want, m.group(0))
        if g.startswith("#ifndef"):
            return "#ifndef __cplusplus\n%s\n#else\n%s\n#endif" % (want, m.group(0))
        return want + "   /* PORT: the corpus's type */"
    out = re.sub(r"^extern\s+([^;(){}=]*?)\b(g_\w+)\s*((?:\[[^\]]*\]\s*)*);", glob_decl, out, flags=re.M)
    declared = set(re.findall(r"^extern\s+[^;]*?\b(\w+)\s*(?:\[[^\]]*\]\s*)*;", out, re.M)) | \
        set(re.findall(r"\b(\w+)\s*\([^;{}]*\)\s*;", out))
    extra = []
    for name in sorted(cg):
        if name not in declared:
            g = guarded(cg[name], name, known_c, known_cpp)
            if g:
                extra.append(g)
    for name, decl, why in GLOBAL_TYPES:
        out, n = re.subn(r"^extern [^;\n]*\b%s\b[^;\n]*;.*$" % re.escape(name),
                         lambda m: "%s   /* PORT: %s */" % (decl, why), out, flags=re.M)
        if n < 1:
            sys.exit("gen_headers: GLOBAL_TYPES: no declaration of %s" % name)
    known = known_cpp
    for name, why in SIZE_FROM_CORPUS.items():
        out, n = re.subn(r"_Static_assert\(sizeof\(%s\) == \d+, \"[^\"]*\"\);" % re.escape(name),
                         "/* PORT: no size check for %s: %s */" % (name, why), out)
        if n != 1:
            sys.exit("gen_headers: no size check for %s in colonization.h" % name)
    # W9: a record holding pointers is the game's size where a pointer is 4 bytes, and 4 bytes
    # more per pointer on a 64-bit target -- the check stays exact on both
    for name, ptrs in POINTER_MEMBERS.items():
        out, n = re.subn(r"_Static_assert\(sizeof\(%s\) == (\d+), " % re.escape(name),
                         lambda m: "_Static_assert(sizeof(%s) == %s + %d * (sizeof(void *) - 4), " % (name, m.group(1), ptrs),
                         out)
        if name == "Resource" and n != 1:
            sys.exit("gen_headers: no size check for %s in colonization.h" % name)
    out = out.replace("_Static_assert(", "PORT_SIZE_ASSERT(")
    macro = ("/* PORT: _Static_assert is C11; the C++ reconstructions compile as C++03. */\n"
             "#ifndef PORT_SIZE_ASSERT\n#ifdef __cplusplus\n"
             "#define PORT_SIZE_ASSERT(cond, msg) typedef char PORT_SA_CAT(port_size_assert_, __LINE__)[(cond) ? 1 : -1]\n"
             "#define PORT_SA_CAT(a, b) PORT_SA_CAT2(a, b)\n#define PORT_SA_CAT2(a, b) a##b\n"
             "#else\n#define PORT_SIZE_ASSERT(cond, msg) _Static_assert(cond, msg)\n#endif\n#endif\n\n")
    first = out.index("#include <stdint.h>")
    out = out[:first] + macro + out[first:]
    # prototypes the corpus has moved on from: a function src/ defines gets its definition's head
    heads = definition_heads()
    fixed, dropped = [], []

    cf_all = corpus_functions()

    def proto(m):
        name = m.group(2)
        want = heads.get(name)
        if want is None and name in cf_all:
            # not defined in src/ (the runtime's, the assembly's): the corpus's one signature
            sigs = {signature(d) for d in cf_all[name]}
            if len(sigs) == 1 and None not in sigs and sigs != {signature(m.group(0))}:
                best = sorted(cf_all[name].items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
                want = re.sub(r'^extern\s+(?:"C"\s+)?', "", best).rstrip(";").strip()
        if want and re.sub(r"\s+", " ", m.group(1)).strip() != want:
            g = guarded("extern %s;" % want, name, known_c, known_cpp)
            if g:
                fixed.append(name)
                return g
            dropped.append(name)
            return "/* PORT: %s's prototype here was stale, and its definition names a type no header has */" % name
        return m.group(0)
    out = re.sub(r"^extern\s+([^;{}()]*?\b([A-Za-z_]\w*)\s*\([^;{}()]*\))\s*;", proto, out, flags=re.M)
    # every function src/ defines that nothing here declares yet, from its definition
    declared |= set(re.findall(r"\b(\w+)\s*\([^;{}]*\)\s*;", out))
    # a function some source file declares itself keeps that file's declaration: a second one
    # here, spelled from the definition, would conflict with it
    own = own_funcs
    protos = []
    for name, head in sorted(heads.items()):
        if name in own and own[name] != {signature(head + ";")}:
            continue        # a file declares it some other way: that file's declaration stands
        if name in declared or "::" in head or re.match(r"\s*(static|inline)\b", head) or "operator" in head:
            continue
        g = guarded("extern %s;" % head, name, known_c, known_cpp)
        if g:
            protos.append(g)
    # functions src/ calls but does not define (the assembly segments', refused files'): the
    # corpus's own declaration, when all its spellings have one signature and every file in src/
    # that declares the function agrees
    cf = corpus_functions()
    for name in sorted(cf):
        if name in heads or name in declared:
            continue
        sigs = {signature(d) for d in cf[name]}
        if len(sigs) != 1 or None in sigs or (name in own and own[name] != sigs):
            continue
        best = sorted(cf[name].items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
        decl = best if best.startswith("extern") else "extern " + best
        g = guarded(decl, name, known_c, known_cpp)
        if g:
            protos.append(g)
    tail = ["", "/* PORT: globals the corpus declares that the model's header does not */"] + extra + \
        ["", "/* PORT: functions src/ defines that the model's header does not declare */"] + protos + [""]
    i = out.rindex("#ifdef __cplusplus\n}")
    out = out[:i] + "\n".join(tail) + "\n" + out[i:]
    return BANNER % "colonization.h" + out, (fixed, dropped, gfix, extra, protos)


def gen_records(col_types):
    src = open(os.path.join(INC, "records.h")).read()
    keep, dropped = [], []
    # each statement of the header: a record dropped when colonization.h defines it
    t = src
    pos = 0
    pieces = []
    for m in re.finditer(r"typedef\s+struct\s*\w*\s*\{", t):
        if m.start() < pos:
            continue
        d = 0
        for j in range(m.end() - 1, len(t)):
            if t[j] == "{":
                d += 1
            elif t[j] == "}":
                d -= 1
                if d == 0:
                    break
        e = t.index(";", j) + 1
        name = re.match(r"\}\s*(\w+)", t[j:]).group(1)
        pieces.append((m.start(), e, name))
        pos = e
    out, last = [], 0
    for s, e, name in pieces:
        out.append(t[last:s])
        out.append(t[s:e])
        keep.append(name)
        if name in col_types:
            dropped.append(name)       # colonization.h's own definition of it goes
        last = e
    out.append(t[last:])
    text = widen_records("".join(out))
    text = text.replace('#include "w16types.h"', '#include "w16types.h"\n#include "port/types.h"\n' + PACK_OPEN, 1)
    text = text.replace("\n#endif", "\n" + PACK_CLOSE + "#endif", 1) if "\n#endif" in text else text + PACK_CLOSE
    return BANNER % "records.h" + text, keep, dropped


# classes the corpus never put in classes.h (every file that used one defined it for itself):
# include/port/corpus_classes.h holds them once, C++ class and C view
CORPUS_CLASSES_H = os.path.join(ROOT, "include", "port", "corpus_classes.h")


def corpus_classes():
    """(C++ definitions, C views, class names, view names) from include/port/corpus_classes.h."""
    t = open(CORPUS_CLASSES_H).read()
    body = t[t.index("#ifdef __cplusplus") + len("#ifdef __cplusplus"):t.rindex("#endif", 0, t.rindex("#endif"))]
    cpp, c = body.split("#else", 1)
    cpp, c = strip_comments(cpp).strip() + "\n", strip_comments(c).strip() + "\n"
    return cpp, c, re.findall(r"\bclass\s+(\w+)\s*(?::[^{;]*)?\{", cpp), re.findall(r"\}\s*(\w+)\s*;", c)


CORPUS_CLASSES, CORPUS_VIEWS = corpus_classes()[2:]


# Borland's vtable pointer is a near pointer, 2 bytes; GCC's is 4, which moves every member of
# every polymorphic class (and the C views, and the corpus's raw base offsets such as
# `(char *)o + 0x26`) by 2 per vtable. The game has ONE virtual function, ResizePort, which
# only GRPort and GameWin define. So the port has no virtual function: GRPort's first member is
# the 2-byte `vptr` Borland had there, holding a class tag (0 GRPort, 1 GameWin and every class
# derived from it, set by GameWin's constructor), and GRPort::ResizePort dispatches on it to
# the two classes' own versions, renamed ResizePort_own (src/host/cxx_glue.c). Every class then
# lays out as the game's does, byte for byte.
DEVIRTUALIZE = [
    ("class GRPort { public: ", "class GRPort { public: i16 vptr; "),
    ("GRPort(); ~GRPort(); virtual int ResizePort(RECT far *r); };",
     "GRPort(); ~GRPort(); int ResizePort(RECT far *r); int ResizePort_own(RECT far *r); };"),
    ("GameWin(); ~GameWin(); virtual int ResizePort(RECT far *r); };",
     "GameWin(); ~GameWin(); int ResizePort_own(RECT far *r); };"),
]


def devirtualize(text):
    for a, b in DEVIRTUALIZE:
        if text.count(a) != 1:
            sys.exit("gen_headers: DEVIRTUALIZE: `%s` is not in classes.h once" % a)
        text = text.replace(a, b)
    if "virtual" in re.sub(r"/\*.*?\*/", "", text, flags=re.S):
        sys.exit("gen_headers: classes.h has a virtual function DEVIRTUALIZE does not handle")
    return text


def gen_classes():
    src = open(os.path.join(INC, "classes.h")).read()
    cpp, c, names, views = corpus_classes()
    note = "/* PORT: %s from include/port/corpus_classes.h: the corpus defined %s in each file (W1) */\n"
    i = src.index("#else")
    src = src[:i] + note % (", ".join(names), "these") + cpp + src[i:]
    j = src.rindex("#endif", 0, src.rindex("#endif"))
    src = src[:j] + note % (", ".join(views), "these") + c + src[j:]
    text = borland_pragmas(widen_records(devirtualize(src)))
    text = text.replace('#include "records.h"', '#include "records.h"\n#include "port/types.h"\n' + PACK_OPEN, 1)
    # the classes are the game's size now: say so where C++ sees them
    asserts = ("#ifdef __cplusplus\n/* PORT: no vtable pointer of GCC's -- the game's layout (gen_headers DEVIRTUALIZE) */\n"
               "PORT_SIZE_ASSERT(sizeof(GRPort) == 0x26 + %d * (sizeof(void *) - 4), \"GRPort is not the game's 0x26 bytes\");\n"
               "PORT_SIZE_ASSERT(sizeof(GameWin) == 0xc4 + %d * (sizeof(void *) - 4), \"GameWin is not the game's 0xc4 bytes\");\n#endif\n"
               % (POINTER_MEMBERS["GRPort"], POINTER_MEMBERS["GameWin"]))
    i = text.rindex("#endif")
    text = text[:i] + asserts + text[i:]
    i = text.rindex("#endif")
    text = text[:i] + PACK_CLOSE + text[i:]
    return BANNER % "classes.h" + text


def gen_w16types():
    src = open(os.path.join(INC, "w16types.h")).read()
    text = widen_records(src)
    i = text.index("#define W16TYPES_H") + len("#define W16TYPES_H\n")
    text = text[:i] + '\n#include "port/types.h"\n' + PACK_OPEN + text[i:]
    j = text.rindex("#endif")
    text = text[:j] + PACK_CLOSE + text[j:]
    return BANNER % "w16types.h" + text


def generate():
    col, fixed = gen_colonization()
    col_types = defined_types(open(os.path.join(INC, "colonization.h")).read())
    rec, keep, dropped = gen_records(col_types)
    files = {"colonization.h": col, "records.h": rec, "classes.h": gen_classes(), "w16types.h": gen_w16types()}
    return files, {"prototypes_fixed": fixed, "records_kept": keep, "records_dropped": dropped}


def main(argv):
    files, info = generate()
    if "--check" in argv:
        stale = [n for n, t in files.items()
                 if not os.path.exists(os.path.join(GEN, n)) or open(os.path.join(GEN, n)).read() != t]
        print("include/gen: %s" % ("current" if not stale else "STALE: " + ", ".join(stale)))
        return 1 if stale else 0
    os.makedirs(GEN, exist_ok=True)
    for n, t in files.items():
        open(os.path.join(GEN, n), "w").write(t)
    f, d, g, x, p = info["prototypes_fixed"]
    print("include/gen: %s; colonization.h: %d prototypes take their definition's head, %d stale ones "
          "dropped; %d globals take the corpus's type, %d more declared; %d prototypes added; "
          "records.h keeps %d" % (", ".join(sorted(files)), len(f), len(d), len(g), len(x), len(p),
                                  len(info["records_kept"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
